-- Schema PostgreSQL (Neon).
-- Convenções:
--  * Dinheiro em centavos (INTEGER/BIGINT) — sem ponto flutuante.
--  * Quantidades em milésimos da unidade (qty_milli): UN/PCT 1000 = 1 un | L 1000 = 1 L (1 = 1 mL) | KG 1000 = 1 kg.
--  * Datas em texto ISO-8601 UTC (ordenáveis); conversão para o fuso do estabelecimento na aplicação.

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('ADMIN','OPERADOR')),
  is_super_admin INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1,
  cash_code_hash TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX uq_users_username ON users (lower(username));

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_by INTEGER REFERENCES users(id),
  updated_at TEXT NOT NULL
);

CREATE TABLE categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX uq_categories_name ON categories (lower(name));

CREATE TABLE products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  internal_code TEXT UNIQUE,
  barcode TEXT UNIQUE,
  category_id INTEGER NOT NULL REFERENCES categories(id),
  unit TEXT NOT NULL CHECK (unit IN ('UN','PCT','L','KG')),
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
  cost_cents INTEGER CHECK (cost_cents IS NULL OR cost_cents >= 0),
  stock_milli BIGINT NOT NULL DEFAULT 0,
  min_stock_milli BIGINT NOT NULL DEFAULT 0,
  track_expiry INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX idx_products_category ON products(category_id);

CREATE TABLE product_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id),
  user_id INTEGER REFERENCES users(id),
  field TEXT NOT NULL,
  old_value TEXT,
  new_value TEXT,
  at TEXT NOT NULL
);
CREATE INDEX idx_product_history_product ON product_history(product_id);

CREATE TABLE payment_methods (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('CASH','PIX','CARD','CREDIT')),
  active INTEGER NOT NULL DEFAULT 1,
  sort INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  notes TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

-- Vários caixas abertos ao mesmo tempo, no máximo um por usuário.
CREATE TABLE cash_registers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status TEXT NOT NULL CHECK (status IN ('OPEN','CLOSED')),
  opened_by INTEGER NOT NULL REFERENCES users(id),
  opened_at TEXT NOT NULL,
  opening_float_cents INTEGER NOT NULL CHECK (opening_float_cents >= 0),
  closed_by INTEGER REFERENCES users(id),
  closed_at TEXT,
  expected_cash_cents BIGINT,
  counted_cash_cents BIGINT,
  summary_json TEXT
);
CREATE UNIQUE INDEX uq_open_register_per_user ON cash_registers(opened_by) WHERE status = 'OPEN';

CREATE TABLE cash_movements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  register_id INTEGER NOT NULL REFERENCES cash_registers(id),
  type TEXT NOT NULL CHECK (type IN ('SUPRIMENTO','SANGRIA')),
  amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
  reason TEXT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  at TEXT NOT NULL
);
CREATE INDEX idx_cash_movements_register ON cash_movements(register_id);

CREATE TABLE tabs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
  opened_by INTEGER NOT NULL REFERENCES users(id),
  opened_at TEXT NOT NULL,
  closed_at TEXT
);
CREATE UNIQUE INDEX uq_open_tab_label ON tabs(label) WHERE status = 'OPEN';

CREATE TABLE tab_people (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tab_id INTEGER NOT NULL REFERENCES tabs(id),
  name TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE sales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key TEXT NOT NULL UNIQUE,
  register_id INTEGER NOT NULL REFERENCES cash_registers(id),
  user_id INTEGER NOT NULL REFERENCES users(id),
  payment_method_id INTEGER NOT NULL REFERENCES payment_methods(id),
  customer_id INTEGER REFERENCES customers(id),
  tab_id INTEGER REFERENCES tabs(id),
  status TEXT NOT NULL CHECK (status IN ('COMPLETED','CANCELLED')),
  subtotal_cents BIGINT NOT NULL,
  surcharge_cents INTEGER NOT NULL DEFAULT 0,
  total_cents BIGINT NOT NULL,
  received_cents BIGINT,
  change_cents BIGINT,
  created_at TEXT NOT NULL,
  cancelled_at TEXT,
  cancelled_by INTEGER REFERENCES users(id),
  cancel_reason TEXT
);
CREATE INDEX idx_sales_created ON sales(created_at);
CREATE INDEX idx_sales_register ON sales(register_id);

CREATE TABLE sale_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id INTEGER NOT NULL REFERENCES sales(id),
  product_id INTEGER NOT NULL REFERENCES products(id),
  product_name TEXT NOT NULL,
  category_id INTEGER NOT NULL REFERENCES categories(id),
  unit TEXT NOT NULL,
  qty_milli BIGINT NOT NULL CHECK (qty_milli > 0),
  unit_price_cents INTEGER NOT NULL,
  unit_cost_cents INTEGER,
  total_cents BIGINT NOT NULL,
  tab_person_id INTEGER REFERENCES tab_people(id)
);
CREATE INDEX idx_sale_items_sale ON sale_items(sale_id);
CREATE INDEX idx_sale_items_product ON sale_items(product_id);

CREATE TABLE tab_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tab_id INTEGER NOT NULL REFERENCES tabs(id),
  person_id INTEGER NOT NULL REFERENCES tab_people(id),
  product_id INTEGER NOT NULL REFERENCES products(id),
  product_name TEXT NOT NULL,
  unit TEXT NOT NULL,
  qty_milli BIGINT NOT NULL CHECK (qty_milli > 0),
  unit_price_cents INTEGER NOT NULL,
  total_cents BIGINT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('PENDING','PAID','VOIDED')),
  sale_id INTEGER REFERENCES sales(id),
  added_by INTEGER NOT NULL REFERENCES users(id),
  added_at TEXT NOT NULL,
  voided_by INTEGER REFERENCES users(id),
  voided_at TEXT,
  void_reason TEXT
);
CREATE INDEX idx_tab_items_tab ON tab_items(tab_id);

CREATE TABLE receivables (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  sale_id INTEGER NOT NULL UNIQUE REFERENCES sales(id),
  original_cents BIGINT NOT NULL,
  surcharge_cents INTEGER NOT NULL,
  total_cents BIGINT NOT NULL,
  paid_cents BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL CHECK (status IN ('OPEN','PAID','CANCELLED')),
  created_at TEXT NOT NULL,
  CHECK (paid_cents >= 0 AND paid_cents <= total_cents)
);
CREATE INDEX idx_receivables_customer ON receivables(customer_id);

CREATE TABLE receivable_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key TEXT NOT NULL UNIQUE,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  register_id INTEGER NOT NULL REFERENCES cash_registers(id),
  payment_method_id INTEGER NOT NULL REFERENCES payment_methods(id),
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  user_id INTEGER NOT NULL REFERENCES users(id),
  at TEXT NOT NULL
);

CREATE TABLE receivable_allocations (
  payment_id INTEGER NOT NULL REFERENCES receivable_payments(id),
  receivable_id INTEGER NOT NULL REFERENCES receivables(id),
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  PRIMARY KEY (payment_id, receivable_id)
);

CREATE TABLE stock_movements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id),
  type TEXT NOT NULL CHECK (type IN ('SALE','SALE_CANCEL','ENTRY','ADJUST','LOSS','INVENTORY')),
  qty_milli BIGINT NOT NULL,
  balance_after_milli BIGINT NOT NULL,
  unit_cost_cents INTEGER,
  reason TEXT,
  ref_type TEXT,
  ref_id INTEGER,
  user_id INTEGER NOT NULL REFERENCES users(id),
  at TEXT NOT NULL
);
CREATE INDEX idx_stock_mov_product ON stock_movements(product_id, at);

CREATE TABLE stock_lots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id),
  expiry_date TEXT NOT NULL,
  qty_milli BIGINT NOT NULL,
  movement_id INTEGER REFERENCES stock_movements(id),
  created_at TEXT NOT NULL
);

CREATE TABLE inventory_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  scope TEXT NOT NULL CHECK (scope IN ('FULL','CATEGORY','PARTIAL')),
  category_id INTEGER REFERENCES categories(id),
  blind INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL CHECK (status IN ('OPEN','FINISHED','CANCELLED')),
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  finished_by INTEGER REFERENCES users(id),
  finished_at TEXT,
  applied INTEGER NOT NULL DEFAULT 0,
  item_accuracy DOUBLE PRECISION,
  value_accuracy DOUBLE PRECISION,
  summary_json TEXT
);

CREATE TABLE inventory_session_items (
  session_id INTEGER NOT NULL REFERENCES inventory_sessions(id),
  product_id INTEGER NOT NULL REFERENCES products(id),
  counted_milli BIGINT,
  system_at_count_milli BIGINT,
  unit_cost_cents INTEGER,
  counted_by INTEGER REFERENCES users(id),
  counted_at TEXT,
  PRIMARY KEY (session_id, product_id)
);

CREATE TABLE audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(id),
  action TEXT NOT NULL,
  entity TEXT,
  entity_id INTEGER,
  details_json TEXT,
  at TEXT NOT NULL
);
CREATE INDEX idx_audit_at ON audit_log(at);

