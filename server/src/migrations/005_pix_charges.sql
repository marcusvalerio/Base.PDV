-- Cobranças Pix com confirmação automática (plano Pro). Cada venda Pix "automática" aponta para uma cobrança aprovada.
CREATE TABLE pix_charges (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL DEFAULT 'mercadopago',
  provider_id TEXT UNIQUE,
  amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
  status TEXT NOT NULL CHECK (status IN ('PENDING','APPROVED','CANCELLED','EXPIRED','FAILED')),
  qr_code TEXT,
  expires_at TEXT NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL,
  paid_at TEXT,
  sale_id INTEGER UNIQUE REFERENCES sales(id)
);
CREATE INDEX idx_pix_charges_status ON pix_charges(status);
