-- Mensalidade por Pix direto na chave do dono da plataforma (confirmação manual no painel central).
CREATE TABLE platform_settings (key TEXT PRIMARY KEY, value TEXT NOT NULL, updated_at TEXT NOT NULL);

-- Pago por Pix até esta data (somado ao Stripe/teste/isenção no cálculo de acesso).
ALTER TABLE tenants ADD COLUMN paid_until TEXT;
-- Carência depois que o cliente avisa "Já paguei" (o sistema não para enquanto você confere).
ALTER TABLE tenants ADD COLUMN pix_grace_until TEXT;

CREATE TABLE pix_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  amount_cents INTEGER NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('first','monthly')),
  status TEXT NOT NULL CHECK (status IN ('PENDING','CONFIRMED','REJECTED')),
  reported_by INTEGER,
  reported_at TEXT NOT NULL,
  decided_by INTEGER,
  decided_at TEXT
);
CREATE INDEX idx_pix_payments_status ON pix_payments(status);
