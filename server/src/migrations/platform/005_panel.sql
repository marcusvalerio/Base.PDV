-- Painel central: avisos aos estabelecimentos, notas internas por cliente e data de cancelamento.
CREATE TABLE platform_notices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER REFERENCES tenants(id),   -- NULL = todos os estabelecimentos
  kind TEXT NOT NULL CHECK (kind IN ('info','maintenance','billing','news')),
  title TEXT NOT NULL,
  message TEXT NOT NULL,
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  created_by INTEGER,
  created_at TEXT NOT NULL
);
CREATE INDEX idx_platform_notices_ends ON platform_notices(ends_at);

CREATE TABLE tenant_notes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL REFERENCES tenants(id),
  admin_id INTEGER,
  text TEXT NOT NULL,
  at TEXT NOT NULL
);
CREATE INDEX idx_tenant_notes_tenant ON tenant_notes(tenant_id);

ALTER TABLE tenants ADD COLUMN canceled_at TEXT;
