-- Plataforma (schema public): estabelecimentos, administração central e assinaturas.
-- Os dados de cada estabelecimento ficam no schema próprio dele (t_<id>).

CREATE TABLE tenants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  schema_name TEXT NOT NULL UNIQUE,
  -- SUSPENDED = bloqueado manualmente pelo admin central.
  status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','SUSPENDED')),
  -- Isento de assinatura (cortesia, teste, uso próprio).
  billing_exempt INTEGER NOT NULL DEFAULT 0,
  trial_ends_at TEXT,
  stripe_customer_id TEXT UNIQUE,
  stripe_subscription_id TEXT UNIQUE,
  subscription_status TEXT,
  current_period_end TEXT,
  created_at TEXT NOT NULL
);

-- Login único entre estabelecimentos: o usuário diz a qual estabelecimento pertence.
CREATE TABLE user_directory (
  username_lower TEXT PRIMARY KEY,
  tenant_id INTEGER NOT NULL REFERENCES tenants(id)
);

CREATE TABLE platform_admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX uq_platform_admins_username ON platform_admins (lower(username));

CREATE TABLE platform_sessions (
  token_hash TEXT PRIMARY KEY,
  admin_id INTEGER NOT NULL REFERENCES platform_admins(id),
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

CREATE TABLE platform_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER,
  action TEXT NOT NULL,
  tenant_id INTEGER,
  details_json TEXT,
  at TEXT NOT NULL
);

-- Eventos do Stripe já processados (o Stripe pode reenviar o mesmo evento).
CREATE TABLE stripe_events (
  id TEXT PRIMARY KEY,
  type TEXT NOT NULL,
  received_at TEXT NOT NULL
);
